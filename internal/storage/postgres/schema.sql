CREATE TABLE users (
    id TEXT PRIMARY KEY,
    email TEXT NOT NULL,
    name TEXT NOT NULL,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE team_members (
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK(role IN ('admin', 'member', 'viewer')),
    PRIMARY KEY(team_id, user_id)
);
CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(team_id, name)
);
CREATE TABLE api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    key_prefix TEXT NOT NULL,
    key_hash TEXT NOT NULL UNIQUE,
    max_rpm INTEGER,
    max_rpd INTEGER,
    max_budget DOUBLE PRECISION,
    soft_budget DOUBLE PRECISION,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_api_keys_application_id ON api_keys(application_id);
CREATE TABLE key_allowed_models (
    key_id BIGINT NOT NULL REFERENCES api_keys(id) ON DELETE CASCADE,
    model_name TEXT NOT NULL,
    PRIMARY KEY(key_id, model_name)
);
CREATE TABLE sessions (
    token TEXT PRIMARY KEY,
    data BYTEA NOT NULL,
    expiry TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_sessions_expiry ON sessions(expiry);
CREATE TABLE cost_overrides (
    model_name TEXT PRIMARY KEY,
    cost_map_key TEXT,
    custom_spec TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE usage_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id TEXT NOT NULL,
    api_key_id BIGINT REFERENCES api_keys(id),
    model TEXT NOT NULL,
    provider TEXT NOT NULL,
    endpoint TEXT NOT NULL,
    input_tokens BIGINT NOT NULL DEFAULT 0,
    output_tokens BIGINT NOT NULL DEFAULT 0,
    total_cost DOUBLE PRECISION DEFAULT 0,
    status_code INTEGER NOT NULL,
    latency_ms BIGINT NOT NULL,
    request_time TIMESTAMPTZ NOT NULL,
    is_streaming BOOLEAN NOT NULL DEFAULT FALSE,
    cache_read_tokens BIGINT NOT NULL DEFAULT 0,
    cache_write_tokens BIGINT NOT NULL DEFAULT 0,
    deployment_key TEXT,
    pool_name TEXT,
    ttft_ms BIGINT,
    req_body_snippet TEXT,
    resp_body_snippet TEXT,
    usage_known BOOLEAN NOT NULL DEFAULT FALSE,
    session_id TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_usage_logs_request_time ON usage_logs(request_time);
CREATE INDEX idx_usage_logs_model ON usage_logs(model);
CREATE INDEX idx_usage_logs_api_key_id ON usage_logs(api_key_id);
CREATE INDEX idx_usage_logs_provider_model_time ON usage_logs(provider, model, request_time DESC);
CREATE INDEX idx_usage_logs_pool_name ON usage_logs(pool_name) WHERE pool_name IS NOT NULL;
CREATE INDEX idx_usage_logs_session_time ON usage_logs(session_id, request_time DESC) WHERE session_id <> '';
CREATE TABLE provider_pools (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    strategy TEXT NOT NULL DEFAULT 'weighted-round-robin',
    budget_cap_daily DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE routing_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_name TEXT NOT NULL,
    model_name TEXT NOT NULL,
    weight INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(pool_name, model_name)
);
CREATE TABLE pool_budget_state (
    pool_name TEXT PRIMARY KEY,
    spend_today DOUBLE PRECISION NOT NULL DEFAULT 0,
    reset_date DATE NOT NULL
);
CREATE TABLE sticky_routing_sessions (
    session_key TEXT PRIMARY KEY,
    pool_name TEXT NOT NULL,
    deployment_key TEXT NOT NULL,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_sticky_routing_sessions_last_used_at ON sticky_routing_sessions(last_used_at);
CREATE TABLE webhook_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    events TEXT NOT NULL,
    secret TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE notification_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_notification_events_created_at ON notification_events(created_at);
CREATE INDEX idx_notification_events_event_type ON notification_events(event_type);
CREATE TABLE webhook_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT REFERENCES webhook_subscriptions(id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES notification_events(id) ON DELETE CASCADE,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    last_attempt_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'pending',
    response_code INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_webhook_deliveries_subscription_id ON webhook_deliveries(subscription_id);
CREATE TABLE responses_jobs (
    id TEXT PRIMARY KEY,
    api_key_id BIGINT,
    deployment_key TEXT NOT NULL,
    model_name TEXT NOT NULL,
    pool_name TEXT,
    status TEXT NOT NULL,
    request_json TEXT NOT NULL,
    response_json TEXT,
    error_json TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    session_id TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_responses_jobs_status ON responses_jobs(status);
